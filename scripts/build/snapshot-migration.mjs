import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
export const migrationPath='supabase/migrations/20261104123719_portfolio_snapshot_release.sql';
const root=new URL('../../',import.meta.url);
export const proposals=['portfolio-item-snapshots','atomic-library-update','atomic-library-create','snapshot-upload-validation','snapshot-transition-read','snapshot-portfolio-copy','snapshot-storage-retention'];
export function buildSnapshotMigration(){
 const header=`-- Generated by scripts/build/snapshot-migration.mjs; do not edit generated body.
-- NOT APPROVED FOR HOSTED INSTALLATION. Read SNAPSHOT_RELEASE_RUNBOOK.md first.
-- Prerequisites: existing portfolio actions/manual age/visibility and image-limit migration.
-- Does not backfill snapshots, delete files, or enable the frontend flag.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';
DO $$ BEGIN
 IF to_regprocedure('public.enforce_library_image_limit()') IS NULL
 OR to_regprocedure('public.perform_portfolio_action(uuid,text,uuid,text)') IS NULL
 OR to_regclass('public.portfolio_section_visibility') IS NULL
 OR NOT EXISTS(SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='profiles' AND column_name='manual_age') THEN
  RAISE EXCEPTION 'Snapshot prerequisites missing' USING ERRCODE='55000';
 END IF;
 IF to_regnamespace('portfolio_private') IS NOT NULL
 OR EXISTS(SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name IN ('portfolio_educations','portfolio_activities','portfolio_certificates') AND column_name='snapshot_data') THEN
  RAISE EXCEPTION 'Snapshot installation already present or partial; inspect before proceeding' USING ERRCODE='55000';
 END IF;
END $$;
`;
 const bodies=proposals.map(name=>{
  const source=readFileSync(new URL(`supabase/proposals/${name}.sql`,root),'utf8');
  const start=source.indexOf('\nBEGIN;'); const end=source.lastIndexOf('\nCOMMIT;');
  if(start<0||end<start||source.slice(end+8).trim())throw new Error('Unexpected proposal wrapper: '+name);
  const body=source.slice(start+8,end);
  if(/^\s*(BEGIN|COMMIT|ROLLBACK);\s*$/m.test(body))throw new Error('Nested transaction in '+name);
  return `-- Source: ${name}.sql SHA256 ${createHash('sha256').update(source).digest('hex')}\n${body}\n`;
 });
 return header+bodies.join('\n')+"\nNOTIFY pgrst, 'reload schema';\nCOMMIT;\n";
}
if(process.argv[1]===fileURLToPath(import.meta.url)){
 const output=new URL(migrationPath,root);const sql=buildSnapshotMigration();
 if(process.argv.length!==3||!['--check','--write'].includes(process.argv[2]))throw new Error('Use --check or --write');
 if(process.argv[2]==='--write')writeFileSync(output,sql);
 else if(readFileSync(output,'utf8')!==sql)throw new Error('Migration differs from reviewed proposals; regenerate and retest');
 console.log('PASS snapshot migration '+process.argv[2]);
}
